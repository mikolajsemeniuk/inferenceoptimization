// Benchmark: model cascade. A cheap model (more quantized or smaller, no thinking) answers first;
// the strong model (reference, thinking) is called only when the cheap answer is not trusted.
// Every request logs both models' answers and all confidence signals, so each cascade policy
// below is evaluated on identical data:
//
//	cheap, strong            the two endpoints
//	consistency-T            escalate when fewer than T of the cheap samples agree
//	verify                   escalate when the cheap model rejects its own answer
//	oracle                   escalate exactly when the cheap answer is wrong (upper bound)
//
//	make bench-cascade
package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"strings"

	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/bench"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/cascade"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/dataset"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/llm"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/metrics"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/output"
	"github.com/mikolajsemeniuk/inferenceoptimization/pkg/run"
)

const samples = 3

type row struct {
	dataset.Example
	Cheap        llm.Response   `json:"cheap"` // greedy cheap answer
	CheapScore   float64        `json:"cheap_score"`
	Samples      []llm.Response `json:"samples"`    // sampled cheap answers for self-consistency
	Agreement    float64        `json:"agreement"`  // share of samples agreeing with the majority
	VoteScore    float64        `json:"vote_score"` // is the majority answer correct
	Verified     bool           `json:"verified"`   // cheap model accepts its greedy answer
	Verification llm.Response   `json:"verification"`
	Strong       llm.Response   `json:"strong"`
	StrongScore  float64        `json:"strong_score"`
	Error        string         `json:"error,omitempty"`
}

type summary struct {
	Task         string  `json:"task"`
	CheapTag     string  `json:"cheap"`
	Policy       string  `json:"policy"`
	N            int     `json:"n"`
	Score        float64 `json:"score"`
	Escalation   float64 `json:"escalation_rate"`
	Latency      float64 `json:"mean_latency_s"`         // sequential: cheap calls (+ strong when escalated)
	Tokens       float64 `json:"mean_completion_tokens"` // all generated tokens, both models
	StrongTokens float64 `json:"mean_strong_tokens"`     // tokens generated by the strong model
}

func main() {
	strong := flag.String("strong-url", "http://localhost:8101", "strong model (thinking)")
	cheap := flag.String("cheap-url", "http://localhost:8102", "cheap model (no thinking)")
	tag := flag.String("tag", "cheap", "label of the cheap model, e.g. Q3_K_M")
	tasks := flag.String("tasks", "gsm8k,mmlu,mmlupro", "comma-separated tasks")
	n := flag.Int("n", 200, "examples per task")
	workers := flag.Int("workers", 8, "concurrent examples")
	reuse := flag.String("strong-from", "output/baseline/Q8_0/think/", "reuse strong answers logged by the baseline run (same examples); empty = ask the strong model")
	flag.Parse()
	ctx := context.Background()

	logged := map[string]bench.Row{} // strong answers from the baseline run, by example id
	if *reuse != "" {
		for _, task := range strings.Split(*tasks, ",") {
			rows, _ := dataset.JSONL[bench.Row](*reuse + task + ".jsonl")
			for _, r := range rows {
				if r.Error == "" {
					logged[r.ID] = r
				}
			}
		}
		fmt.Println("strong answers reused from baseline:", len(logged))
	}

	answer := func(e dataset.Example) row {
		r := row{Example: e}
		fail := func(err error) row { r.Error = err.Error(); return r }
		var err error
		if r.Cheap, err = llm.Chat(ctx, *cheap, llm.Request{Messages: llm.User(e.Text()), MaxTokens: 1024, Extra: llm.Think(false)}); err != nil {
			return fail(err)
		}
		r.CheapScore = dataset.Grade(e, r.Cheap.Content)
		var votes []string
		for s := range samples {
			extra := llm.Think(false)
			extra["temperature"] = 0.7
			res, err := llm.Chat(ctx, *cheap, llm.Request{Messages: llm.User(e.Text()), MaxTokens: 1024, Seed: s + 1, Extra: extra})
			if err != nil {
				return fail(err)
			}
			r.Samples = append(r.Samples, res)
			votes = append(votes, dataset.Extract(e, res.Content))
		}
		winner, agreement := cascade.Vote(votes)
		r.Agreement = agreement
		for i, v := range votes {
			if v == winner {
				r.VoteScore = dataset.Grade(e, r.Samples[i].Content)
				break
			}
		}
		if r.Verified, r.Verification, err = cascade.Verify(ctx, *cheap, e.Text(), r.Cheap.Content); err != nil {
			return fail(err)
		}
		if b, ok := logged[e.ID]; ok {
			r.Strong, r.StrongScore = b.Response, b.Score
			return r
		}
		if r.Strong, err = llm.Chat(ctx, *strong, llm.Request{Messages: llm.User(e.Text()), MaxTokens: 4096, Extra: llm.Think(true)}); err != nil {
			return fail(err)
		}
		r.StrongScore = dataset.Grade(e, r.Strong.Content)
		return r
	}

	// policy = (cost and score of the cheap stage, should we escalate)
	type stage struct {
		score, latency, tokens float64
		escalate               bool
	}
	sampled := func(r row) (latency, tokens float64) {
		for _, s := range r.Samples {
			latency, tokens = max(latency, s.Latency), tokens+float64(s.CompletionTokens) // samples run in parallel
		}
		return
	}
	policies := []struct {
		name string
		f    func(row) stage
	}{
		{"cheap", func(r row) stage {
			return stage{r.CheapScore, r.Cheap.Latency, float64(r.Cheap.CompletionTokens), false}
		}},
		{"strong", func(r row) stage { return stage{0, 0, 0, true} }},
		{"consistency-2of3", func(r row) stage {
			l, t := sampled(r)
			return stage{r.VoteScore, l, t, cascade.Escalate(r.Agreement, 2.0/3)}
		}},
		{"consistency-3of3", func(r row) stage {
			l, t := sampled(r)
			return stage{r.VoteScore, l, t, cascade.Escalate(r.Agreement, 1)}
		}},
		{"verify", func(r row) stage {
			return stage{r.CheapScore, r.Cheap.Latency + r.Verification.Latency, float64(r.Cheap.CompletionTokens + r.Verification.CompletionTokens), !r.Verified}
		}},
		{"oracle", func(r row) stage {
			return stage{r.CheapScore, r.Cheap.Latency, float64(r.Cheap.CompletionTokens), r.CheapScore < 1}
		}},
	}

	dir := "output/cascade/" + *tag + "/"
	var summaries []summary
	for _, task := range strings.Split(*tasks, ",") {
		examples, err := dataset.Load(task)
		if err != nil {
			log.Fatal(err)
		}
		rows := run.Map(dataset.Sample(examples, *n, 1), *workers, func(_ int, e dataset.Example) row { return answer(e) })
		for _, p := range policies {
			s := summary{Task: task, CheapTag: *tag, Policy: p.name}
			var score, latency, tokens, strongTokens []float64
			escalated := 0
			for _, r := range rows {
				if r.Error != "" {
					continue
				}
				st := p.f(r)
				if st.escalate {
					escalated++
					st.score, st.latency, st.tokens = r.StrongScore, st.latency+r.Strong.Latency, st.tokens+float64(r.Strong.CompletionTokens)
					strongTokens = append(strongTokens, float64(r.Strong.CompletionTokens))
				} else {
					strongTokens = append(strongTokens, 0)
				}
				score, latency, tokens = append(score, st.score), append(latency, st.latency), append(tokens, st.tokens)
			}
			s.N, s.Score, s.Escalation = len(score), metrics.Mean(score), metrics.Rate(escalated, len(score))
			s.Latency, s.Tokens, s.StrongTokens = metrics.Mean(latency), metrics.Mean(tokens), metrics.Mean(strongTokens)
			summaries = append(summaries, s)
			fmt.Printf("%-10s %-8s %-17s n=%d score=%.3f escalation=%.2f latency=%.1fs tokens=%.0f\n", *tag, task, p.name, s.N, s.Score, s.Escalation, s.Latency, s.Tokens)
		}
		if err := output.JSONL(dir+task+".jsonl", rows); err != nil {
			log.Fatal(err)
		}
		if err := output.JSON(dir+"summary.json", summaries); err != nil {
			log.Fatal(err)
		}
	}
}
